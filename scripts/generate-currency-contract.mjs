import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const contract = {
  source: '../src/shared/domain/currencies.ts',
  swiftOutput: '../../UFit/Core/Models/CurrencyMinorUnits.generated.swift',
  sourceDeclaration: /export const CURRENCY_MINOR_UNITS = (\{[\s\S]*?\}) as const;/,
  codePattern: /^[A-Z]{3}$/,
  minimumDigits: 0,
  maximumDigits: 4,
  digestAlgorithm: 'sha256',
  encoding: 'utf8',
  argument: {check: '--check', output: '--output'},
  failure: {
    arguments: 'Usage: node scripts/generate-currency-contract.mjs [--check] [--output path]',
    declaration: 'Canonical currency declaration is missing',
    table: 'Canonical currency table is invalid',
    drift: 'Swift currency contract differs from its canonical source; regenerate it',
  },
};

function options(args) {
  let check = false;
  let output;
  for (let index = 0; index < args.length; index++) {
    const argument = args[index];
    if (argument === contract.argument.check && !check) check = true;
    else if (argument === contract.argument.output && output === undefined && args[index + 1]
      && !args[index + 1].startsWith('--')) output = args[++index];
    else throw new Error(contract.failure.arguments);
  }
  return {check, output};
}

function swiftContract(source) {
  const match = source.match(contract.sourceDeclaration);
  if (!match) throw new Error(contract.failure.declaration);
  const entries = Object.entries(JSON.parse(match[1]));
  if (!entries.length || entries.some(([code, digits]) => !contract.codePattern.test(code)
    || !Number.isInteger(digits) || digits < contract.minimumDigits || digits > contract.maximumDigits)) {
    throw new Error(contract.failure.table);
  }
  const sourceDigest = createHash(contract.digestAlgorithm).update(source).digest('hex');
  const rows = entries.map(([code, digits]) => `        "${code}": ${digits},`).join('\n');
  return `// Generated by UFit_backend/scripts/generate-currency-contract.mjs. Do not edit.
// Ufit accounting precision comes from the canonical table, never locale display defaults.
enum UFitCurrencyMinorUnits {
    static let sourceSHA256 = "${sourceDigest}"
    private static let digitsByCode: [String: Int] = [
${rows}
    ]

    static func digits(for code: String) -> Int? { digitsByCode[code] }
}
`;
}

const directory = dirname(fileURLToPath(import.meta.url));
const settings = options(process.argv.slice(2));
const output = settings.output === undefined ? resolve(directory, contract.swiftOutput) : resolve(settings.output);
const source = readFileSync(resolve(directory, contract.source), contract.encoding);
const generated = swiftContract(source);
if (settings.check) {
  if (readFileSync(output, contract.encoding) !== generated) throw new Error(contract.failure.drift);
} else writeFileSync(output, generated, contract.encoding);
process.stdout.write(settings.check ? 'Swift currency contract and source fingerprint match.\n' : 'Swift currency contract generated.\n');
